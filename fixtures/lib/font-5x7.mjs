export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

/**
 * The 7 × 5 ink mask for one character.
 *
 * @param {string} char  a single code point
 * @returns {boolean[][]} rows of columns, `true` where there is ink
 */
export function glyph(char) {
  const rows = GLYPHS[char];
  if (rows === undefined) {
    throw new Error(
      `the 5x7 fixture font has no glyph for ${JSON.stringify(char)} ` +
        `(U+${char.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}); ` +
        'add one to fixtures/lib/font-5x7.mjs rather than dropping the character',
    );
  }
  return rows.split('/').map((row) => [...row].map((cell) => cell === '#'));
}

/** Every character the font can draw, so a caller can assert a string is drawable up front. */
export function drawable(text) {
  return [...text].every((char) => GLYPHS[char] !== undefined);
}

/* Fail at import time rather than halfway through a page if a glyph was mistyped to the wrong
   width or height. Cheap, and the table is edited by hand. */
for (const [char, rows] of Object.entries(GLYPHS)) {
  const lines = rows.split('/');
  if (lines.length !== GLYPH_HEIGHT || lines.some((line) => line.length !== GLYPH_WIDTH)) {
    throw new Error(`glyph ${JSON.stringify(char)} is not ${GLYPH_WIDTH}x${GLYPH_HEIGHT}`);
  }
}
