/** ISBN-13 check digit, alternating weights 1 and 3, modulo 10. */
export const isValidIsbn13 = (digits: string): boolean => {
  if (!/^\d{13}$/.test(digits)) return false;
  let sum = 0;
  for (let index = 0; index < 13; index += 1) {
    sum += Number(digits[index]) * (index % 2 === 0 ? 1 : 3);
  }
  return sum % 10 === 0;
};

/** ISSN check digit, weights 8..2, modulo 11, with X for 10. */
export const isValidIssn = (value: string): boolean => {
  if (!/^\d{4}-\d{3}[\dX]$/.test(value)) return false;
  const digits = value.replace('-', '');
  let sum = 0;
  for (let index = 0; index < 7; index += 1) {
    sum += Number(digits[index]) * (8 - index);
  }
  const remainder = (11 - (sum % 11)) % 11;
  const expected = remainder === 10 ? 'X' : String(remainder);
  return digits[7] === expected;
};

/** ORCID check digit: ISO 7064 MOD 11-2 over the 15 leading digits. */
export const isValidOrcid = (value: string): boolean => {
  if (!/^\d{4}-\d{4}-\d{4}-\d{3}[\dX]$/.test(value)) return false;
  const digits = value.replace(/-/g, '');
  let total = 0;
  for (let index = 0; index < 15; index += 1) {
    total = (total + Number(digits[index])) * 2;
  }
  const remainder = total % 11;
  const result = (12 - remainder) % 11;
  const expected = result === 10 ? 'X' : String(result);
  return digits[15] === expected;
};
