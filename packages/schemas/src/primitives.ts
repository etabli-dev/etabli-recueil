export const UrlSchema = z
  .string()
  .max(4096)
  .refine((value) => {
    try {
      const parsed = new URL(value);
      return parsed.protocol === 'http:' || parsed.protocol === 'https:';
    } catch {
      return false;
    }
  }, 'must be an absolute http(s) URL')
  .meta({ id: 'Url', title: 'Url', format: 'uri', examples: ['https://example.org/paper.pdf'] });

/** A short free-text label. Bounded so that a runaway import cannot write a novel into a title. */
export const ShortTextSchema = z.string().min(1).max(1024);
export const LongTextSchema = z.string().max(1_000_000);

/** A non-negative count of things. */
export const CountSchema = z.number().int().min(0);

/**
 * The slug shape used for every extensible vocabulary key: custom field keys, item types, job
 * types, check ids. Lowercase, starts with a letter, no punctuation but the underscore
 * (`spec/data-model.md` §4.6, `ck_custom_fields_key_shape`).
 */
export const SLUG_PATTERN = /^[a-z][a-z0-9_]*$/;
export const SlugSchema = z
  .string()
  .min(1)
  .max(64)
  .regex(SLUG_PATTERN, 'must be a lowercase slug matching [a-z][a-z0-9_]*');

