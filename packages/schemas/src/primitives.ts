/* JSON                                                                                            */
/* -------------------------------------------------------------------------------------------- */

export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

/**
 * Any JSON value. Used where the database column is `JSON` and the content is opaque to SQL.
 *
 * The recursion goes through a single stable instance rather than a fresh one per call, because a
 * lazy schema rebuilt on every access is rendered as a new anonymous component every time it is
 * reached, and the generated document ends up with a `__schema0` per JSON column.
 */
export const JsonValueSchema: z.ZodType<JsonValue> = z.lazy(() => jsonValueUnion).meta({
  id: 'JsonValue',
  title: 'JsonValue',
  description: 'Any JSON value: a string, number, boolean, null, array or object.',
});

const jsonValueUnion = z.union([
  z.string(),
  z.number(),
  z.boolean(),
  z.null(),
  z.array(JsonValueSchema),
  z.record(z.string(), JsonValueSchema),
]);

/** A JSON object. The default for `JSON` columns whose default is `{}`. */
export const JsonObjectSchema = z.record(z.string(), JsonValueSchema).meta({
  id: 'JsonObject',
  title: 'JsonObject',
  description: 'An arbitrary JSON object.',
});

